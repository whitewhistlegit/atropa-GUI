"""
atropa.backend.apparmor
----------------------------
Dedicated AppArmor module: profile listing and enforce/complain/disable
control, denial review (AppArmor's equivalent of an AVC), and real
category-toggle rule editing - network access and capabilities are
distinct rule types in a profile, so toggling them is a genuine on/off
switch, not a simplification.

There's no AppArmor equivalent of `audit2allow` - a suggested rule is
built directly from the denial's own fields (path + requested_mask,
capability name, or network family/sock_type), not generated by a
separate policy tool. That's inherently more of a best-effort guess than
the SELinux side, and the UI should treat it as a starting point to edit,
not a ready-to-apply answer.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from .privilege import CommandResult, backup_file, run_privileged, run_unprivileged

PROFILES_DIR = Path("/etc/apparmor.d")

# Common capability and network rule types worth exposing as direct toggles.
# Each maps to an exact, single-line AppArmor rule - not a category that
# expands into multiple rules - so "on" or "off" is unambiguous.
COMMON_CAPABILITIES = [
    ("net_admin", "Network administration (interfaces, routing, firewall)"),
    ("net_raw", "Raw sockets (e.g. ping, packet capture)"),
    ("sys_admin", "Broad system administration operations"),
    ("sys_ptrace", "Trace/attach to other processes"),
    ("dac_override", "Bypass file read/write/execute permission checks"),
    ("setuid", "Change process UID"),
    ("setgid", "Change process GID"),
]

COMMON_NETWORK_RULES = [
    ("inet stream", "TCP over IPv4"),
    ("inet dgram", "UDP over IPv4"),
    ("inet6 stream", "TCP over IPv6"),
    ("inet6 dgram", "UDP over IPv6"),
    ("unix stream", "Unix domain sockets (stream)"),
    ("unix dgram", "Unix domain sockets (datagram)"),
]


@dataclass
class AppArmorProfile:
    path: str
    mode: str  # "enforce" | "complain" | "kill" | "unconfined"


def is_available() -> bool:
    return shutil.which("aa-status") is not None or Path("/sys/kernel/security/apparmor").exists()


def list_profiles() -> list[AppArmorProfile]:
    """
    Parses `aa-status`'s human-readable output. Requires root to see the
    full profile list (aa-status reads kernel securityfs internals), so
    this is privileged even though it's read-only.
    """
    if not shutil.which("aa-status"):
        raise RuntimeError("aa-status isn't installed. Install it with: pacman -S apparmor")

    result = run_privileged(["aa-status"])
    if not result.ok:
        raise RuntimeError(result.stderr.strip() or "aa-status failed")

    profiles: list[AppArmorProfile] = []
    mode: str | None = None
    for line in result.stdout.splitlines():
        stripped = line.strip()
        header = re.match(r"^\d+\s+profiles are in (\w+) mode", stripped)
        if header:
            mode = header.group(1)
            continue
        if re.match(r"^\d+\s+processes", stripped):
            break  # profile section ends; the rest duplicates entries with PIDs
        if mode and stripped and line.startswith((" ", "\t")):
            profiles.append(AppArmorProfile(path=stripped, mode=mode))
    return profiles


def set_profile_mode(profile_path: str, mode: str) -> CommandResult:
    """mode is one of 'enforce', 'complain', 'disable'."""
    tools = {"enforce": "aa-enforce", "complain": "aa-complain", "disable": "aa-disable"}
    if mode not in tools:
        raise ValueError(f"Unknown mode: {mode}")
    tool = tools[mode]
    if not shutil.which(tool):
        raise RuntimeError(f"'{tool}' isn't installed. Install it with: pacman -S apparmor")
    return run_privileged([tool, profile_path])


# --------------------------------------------------------- profile files --

def _read_file_safely(path: str) -> str:
    """Reads a profile file, falling back to a privileged read if it isn't user-readable."""
    p = Path(path)
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except PermissionError:
        result = run_privileged(["cat", path])
        if not result.ok:
            raise RuntimeError(result.stderr.strip() or f"Could not read {path}")
        return result.stdout


def resolve_profile_file(profile_identifier: str) -> str | None:
    """
    Profile files under /etc/apparmor.d/ are conventionally named by
    replacing '/' with '.' in the confined binary's path (e.g.
    /usr/bin/firefox -> usr.bin.firefox). Falls back to grepping all
    profile files for a 'profile <identifier>' declaration, which also
    catches child profiles, hats, and named (non-path) profiles.
    """
    candidate = PROFILES_DIR / profile_identifier.strip("/").replace("/", ".")
    if candidate.exists():
        return str(candidate)

    if not PROFILES_DIR.exists():
        return None
    result = run_unprivileged(["grep", "-rl", f"profile {profile_identifier}", str(PROFILES_DIR)])
    lines = [l.strip() for l in result.stdout.strip().splitlines() if l.strip()]
    return lines[0] if lines else None


def _insert_before_final_brace(content: str, rule_line: str) -> str:
    idx = content.rstrip().rfind("}")
    if idx == -1:
        raise RuntimeError("Could not find a closing '}' in the profile to insert the rule before")
    return content[:idx] + f"  {rule_line}\n" + content[idx:]


def _write_and_reload(profile_file: str, original: str, new_content: str) -> CommandResult:
    """
    Writes new_content and reloads the profile from it. When apparmor_parser
    rejects the result, the kernel keeps the profile it already had loaded;
    the file is put back to match, so the next boot or reload doesn't trip
    over the rejected version.
    """
    result = run_privileged(["tee", profile_file], input_text=new_content)
    if not result.ok:
        return result
    reload_result = run_privileged(["apparmor_parser", "-r", profile_file])
    if reload_result.ok:
        return reload_result

    problem = reload_result.stderr.strip() or f"apparmor_parser exited with {reload_result.returncode}"
    restore_result = run_privileged(["tee", profile_file], input_text=original)
    if restore_result.ok:
        raise RuntimeError(
            f"apparmor_parser rejected the change: {problem}. Restored the previous profile; the loaded "
            "policy is unchanged."
        )
    raise RuntimeError(
        f"apparmor_parser rejected the change: {problem}. Restoring the previous profile ALSO failed "
        f"({restore_result.stderr.strip() or 'unknown error'}), so {profile_file} still contains the rejected "
        "change - restore it from Activity & Backups before the next reload."
    )


def append_rule_to_profile(profile_file: str, rule_line: str) -> CommandResult:
    """Backs up the profile, appends rule_line before its closing brace, and reloads it."""
    backup_file(profile_file)
    content = _read_file_safely(profile_file)
    new_content = _insert_before_final_brace(content, rule_line.strip())
    return _write_and_reload(profile_file, content, new_content)


def _set_rule_presence(profile_file: str, rule_line: str, present: bool) -> CommandResult:
    """Adds rule_line if present=True and missing, removes it if present=False and there."""
    backup_file(profile_file)
    content = _read_file_safely(profile_file)
    lines = content.splitlines()
    target = rule_line.strip()
    exists = any(l.strip() == target for l in lines)

    if present and not exists:
        new_content = _insert_before_final_brace(content, target)
    elif not present and exists:
        new_content = "\n".join(l for l in lines if l.strip() != target) + "\n"
    else:
        return CommandResult(0, "no change needed", "")

    return _write_and_reload(profile_file, content, new_content)


def set_capability_rule(profile_file: str, capability: str, allow: bool) -> CommandResult:
    return _set_rule_presence(profile_file, f"capability {capability},", allow)


def set_network_rule(profile_file: str, network_spec: str, allow: bool) -> CommandResult:
    return _set_rule_presence(profile_file, f"network {network_spec},", allow)


def profile_toggle_states(profile_file: str) -> dict:
    """Current on/off state for every toggle in COMMON_CAPABILITIES / COMMON_NETWORK_RULES."""
    content = _read_file_safely(profile_file)
    lines = [l.strip() for l in content.splitlines()]
    return {
        "capabilities": {cap: f"capability {cap}," in lines for cap, _desc in COMMON_CAPABILITIES},
        "network": {spec: f"network {spec}," in lines for spec, _desc in COMMON_NETWORK_RULES},
    }


# ---------------------------------------------------------------- denials --

def list_denials(limit: int = 50) -> list[str]:
    """
    Recent 'apparmor="DENIED"' lines from the kernel log. Only complete
    while auditd isn't running: once it is, the kernel hands audit records
    to auditd instead of printing them, so new denials only show up in
    list_denials_from_audit_log().
    """
    result = run_unprivileged(["journalctl", "-k", "--no-pager", "-g", "apparmor=", "-n", str(limit * 3), "--output=cat"])
    lines = [l.strip() for l in result.stdout.strip().splitlines() if l.strip() and "denied" in l.lower()]
    return lines[-limit:]


def list_denials_from_audit_log(limit: int = 50) -> list[str]:
    """
    AppArmor denials since boot from the audit log, where they go while
    auditd runs. The log is root-only, so this needs a password prompt and
    only runs when asked for.
    """
    if not shutil.which("ausearch"):
        raise RuntimeError("ausearch isn't installed. Install it with: pacman -S audit")
    # --input-logs: read the log files even when our stdin is a pipe -
    # otherwise ausearch reads audit records from stdin instead.
    result = run_privileged(["ausearch", "-m", "AVC,APPARMOR_DENIED", "-ts", "boot", "--input-logs"])
    if not result.ok and "<no matches>" not in result.stderr:
        raise RuntimeError(
            f"Couldn't read the audit log: {result.stderr.strip() or f'ausearch exited with {result.returncode}'}"
        )
    lines = [l.strip() for l in result.stdout.splitlines() if 'apparmor="DENIED"' in l]
    return lines[-limit:]


def auditd_running() -> bool:
    """True if auditd is collecting audit records - the kernel log then misses new denials."""
    return run_unprivileged(["systemctl", "is-active", "auditd"]).stdout.strip() == "active"


def _extract_field(raw_line: str, key: str) -> str | None:
    m = re.search(rf'{key}="?([^",\s]+)"?', raw_line)
    return m.group(1) if m else None


def explain_denial(raw_line: str) -> str:
    """
    No 'aa-why' tool exists for AppArmor - this formats the denial's own
    fields into plain text rather than deriving new information.
    """
    fields = {
        "Profile": _extract_field(raw_line, "profile"),
        "Operation": _extract_field(raw_line, "operation"),
        "Target": _extract_field(raw_line, "name"),
        "Requested permission": _extract_field(raw_line, "requested_mask"),
        "Denied permission": _extract_field(raw_line, "denied_mask"),
        "Capability": _extract_field(raw_line, "capname") or _extract_field(raw_line, "capability"),
        "Process": _extract_field(raw_line, "comm"),
    }
    lines = ["This access was blocked by the profile's confinement rules."]
    lines += [f"{label}: {value}" for label, value in fields.items() if value]
    return "\n".join(lines)


def generate_rule_suggestion(raw_line: str) -> str:
    """
    Best-effort suggested rule built directly from the denial's fields.
    Unlike audit2allow, this isn't validated against a policy compiler -
    review it before appending.
    """
    name = _extract_field(raw_line, "name")
    mask = _extract_field(raw_line, "requested_mask")
    capability = _extract_field(raw_line, "capname") or _extract_field(raw_line, "capability")
    family = _extract_field(raw_line, "family")
    sock_type = _extract_field(raw_line, "sock_type")
    operation = _extract_field(raw_line, "operation")

    if name and mask:
        return f"{name} {mask},"
    if capability:
        return f"capability {capability},"
    if family and sock_type:
        # AppArmor network rule grammar is 'network <family> <sock_type>,'
        # (e.g. 'network inet stream,') - NOT family+protocol.
        return f"network {family} {sock_type},"
    return f"# Could not derive a rule automatically (operation={operation or 'unknown'}); edit this by hand."
